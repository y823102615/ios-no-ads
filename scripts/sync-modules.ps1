<#
.SYNOPSIS
  Download the upstream community ad-block module, apply local patches, and write
  the trimmed module to modules/blockAds.trimmed.sgmodule.

.DESCRIPTION
  Upstream: fmz200/wool_scripts Shadowrocket/module/blockAds.srmodule
  Patches:
    1. Remove the "safe browsing bypass" rules. Upstream rejects Apple/Google/QQ/Baidu
       safe-browsing domains; that disables Safari's fraudulent-website warning and is
       not ad blocking.
    2. Remove Bilibili rewrites that fake VIP status in account/mine and account/myinfo.
       They are cosmetic "unlock" hacks, not ad removal, and may confuse the app.
  The script fails if a patch no longer matches anything, so upstream format changes
  are noticed instead of silently ignored.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File scripts\sync-modules.ps1
#>
[CmdletBinding()]
param(
    [string]$UpstreamUrl = 'https://raw.githubusercontent.com/fmz200/wool_scripts/main/Shadowrocket/module/blockAds.srmodule',
    [string]$OutFile = ''
)

$ErrorActionPreference = 'Stop'
# Windows PowerShell 5.1 does not populate $PSScriptRoot inside param defaults.
if (-not $OutFile) {
    $OutFile = Join-Path (Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)) 'modules\blockAds.trimmed.sgmodule'
}
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12

Write-Host "Downloading $UpstreamUrl"
$bytes = (Invoke-WebRequest -UseBasicParsing -Uri $UpstreamUrl -TimeoutSec 120).RawContentStream.ToArray()
$text = [Text.Encoding]::UTF8.GetString($bytes)
$lines = $text -split "`r?`n"
Write-Host "Upstream lines: $($lines.Count)"

# Each patch: a name and a regex. Matching lines are dropped.
$patches = @(
    @{ Name = 'safe-browsing bypass rules';
       Regex = '^(DOMAIN|DOMAIN-SUFFIX),(lookup\.api\.bsb\.baidu\.com|proxy\.safebrowsing\.apple|safebrowsing\.g\.applimg\.com|safebrowsing\.googleapis\.com|safebrowsing\.urlsec\.qq\.com|token\.safebrowsing\.apple|safebrowsing\.apple|vs6\.bj2ct\.u3\.ucweb\.com|u3\.ucweb\.com),REJECT' },
    @{ Name = 'bilibili fake-VIP rewrites';
       Regex = '^http-response-jq \^https:\\/\\/app\\\.bilibili\\\.com\\/x\\/v2\\/account\\/(mine|myinfo)' }
)

$kept = New-Object System.Collections.Generic.List[string]
$removed = @{}
foreach ($p in $patches) { $removed[$p.Name] = 0 }

foreach ($line in $lines) {
    $drop = $false
    foreach ($p in $patches) {
        if ($line -match $p.Regex) { $removed[$p.Name]++; $drop = $true; break }
    }
    if (-not $drop) { $kept.Add($line) }
}

$missing = @()
foreach ($p in $patches) {
    Write-Host ("Removed {0,3} line(s): {1}" -f $removed[$p.Name], $p.Name)
    if ($removed[$p.Name] -eq 0) { $missing += $p.Name }
}
if ($missing.Count -gt 0) {
    throw "Patch matched nothing, upstream format may have changed: $($missing -join ', '). Review the upstream file before publishing."
}

# Rename the module so it is distinguishable from upstream inside Shadowrocket.
for ($i = 0; $i -lt $kept.Count; $i++) {
    if ($kept[$i] -match '^#!name=') {
        # Kept ASCII: PowerShell 5.1 reads BOM-less scripts as ANSI.
        $kept[$i] = '#!name=AdBlock (fmz200, self-trimmed)'
        break
    }
}
$header = "# Generated by scripts/sync-modules.ps1 on $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss') from $UpstreamUrl"
# Insert after the leading "#!" metadata block so the metadata stays contiguous.
$insertAt = 0
while ($insertAt -lt $kept.Count -and $kept[$insertAt] -match '^#!') { $insertAt++ }
$kept.Insert($insertAt, $header)

$outDir = Split-Path -Parent $OutFile
if (-not (Test-Path $outDir)) { New-Item -ItemType Directory -Path $outDir | Out-Null }
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
$OutFile = Join-Path (Resolve-Path -LiteralPath $outDir).Path (Split-Path -Leaf $OutFile)
[IO.File]::WriteAllText($OutFile, ($kept -join "`n"), $utf8NoBom)

$hostLine = $kept | Where-Object { $_ -match '^hostname\s*=' } | Select-Object -Last 1
$hostCount = if ($hostLine) { (($hostLine -replace '^hostname\s*=\s*(%APPEND%)?', '') -split ',').Count } else { 0 }
Write-Host "Wrote $OutFile ($($kept.Count) lines, $hostCount MITM hostnames)"
